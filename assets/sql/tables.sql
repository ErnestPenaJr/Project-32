-- 3. ROOMS
CREATE TABLE ROOMS (
    ROOM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROOM_NAME VARCHAR2(100) NOT NULL,
    BUILDING VARCHAR2(100) NOT NULL,
    ROOM_NUMBER NUMBER NOT NULL,
    CAPACITY NUMBER NOT NULL,
    DESCRIPTION VARCHAR2(500),
    -- VARCHAR2(3) with a 'NO' default live, and no CHECK constraint. The
    -- previous VARCHAR2(20) + CHECK definition here did not match, and the
    -- missing comma after it meant this file could not be executed at all.
    MAINTENANCE_STATUS VARCHAR2(3) DEFAULT 'NO',
    RECURRING VARCHAR2(3) DEFAULT 'NO',
    ROOM_IMAGE CLOB,
    STATUS VARCHAR2(10) DEFAULT 'Active'
);

-- 4. AMENITIES
CREATE TABLE AMENITIES (
    AMENITY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AMENITY_NAME VARCHAR2(100) UNIQUE NOT NULL,
    DESCRIPTION VARCHAR2(500),
    ICON_ID NUMBER,
    CONSTRAINT FK_AMENITIES_ICONS FOREIGN KEY (ICON_ID)
        REFERENCES ICONS(ICON_ID)
);
-- NOTE: this references ICONS, which is created at the end of this file. Create
-- ICONS before AMENITIES, or add the constraint afterwards.

-- 5. ROOM_AMENITIES (Join Table)
CREATE TABLE ROOM_AMENITIES (
    ROOM_ID NUMBER NOT NULL,
    AMENITY_ID NUMBER NOT NULL,
    PRIMARY KEY (ROOM_ID, AMENITY_ID),
    CONSTRAINT FK_ROOM_AMENITIES_ROOMS FOREIGN KEY (ROOM_ID)
        REFERENCES ROOMS(ROOM_ID),
    CONSTRAINT FK_ROOM_AMENITIES_AMENITIES FOREIGN KEY (AMENITY_ID)
        REFERENCES AMENITIES(AMENITY_ID)
);

-- 6. BOOKINGS
CREATE TABLE BOOKINGS (
    BOOKING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Who SUBMITTED the request. Distinct from BOOKED_FOR_* below.
    USER_ID NUMBER NOT NULL,
    ROOM_ID NUMBER NOT NULL,
    START_TIME TIMESTAMP NOT NULL,
    END_TIME TIMESTAMP NOT NULL,
    RECURRING_DETAILS VARCHAR2(500),
    -- Values are lowercase. The old definition here claimed
    -- CHECK (STATUS IN ('Confirmed','Cancelled')), which matched nothing the
    -- application ever writes. Enforced live by CHK_BOOKINGS_STATUS.
    STATUS VARCHAR2(20),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    APPROVED_BY NUMBER(38),
    -- Holds the requester's meeting title / purpose. 1000 chars live, not 500.
    -- Approval must not overwrite this; see assets/cfc/approvals.cfc.
    COMMENTS VARCHAR2(1000),

    -- from add_booking_revision_tracking.sql
    ORIGINAL_BOOKING_ID NUMBER,
    REVISION_NUMBER NUMBER DEFAULT 0 NOT NULL,
    IS_MODIFIED CHAR(1) DEFAULT 'N' CHECK (IS_MODIFIED IN ('Y', 'N')),
    REVISION_DATE TIMESTAMP,
    MODIFIED_BY NUMBER,

    -- from add_reservation_for_and_decision_audit.sql
    -- "Reservation For": who the space is actually for. NULL on records created
    -- before this existed, and the application then falls back to the requester.
    BOOKED_FOR_NAME VARCHAR2(200),
    BOOKED_FOR_EMAIL VARCHAR2(255),
    BOOKED_FOR_DEPARTMENT VARCHAR2(100),
    DECIDED_AT TIMESTAMP,
    DECIDED_BY NUMBER,
    CANCELLED_AT TIMESTAMP,
    CANCELLED_BY NUMBER,
    CANCELLATION_REASON VARCHAR2(1000),

    CONSTRAINT CHK_BOOKINGS_STATUS CHECK
        (STATUS IN ('pending', 'approved', 'rejected', 'cancelled', 'archived')),
    CONSTRAINT FK_BOOKINGS_USERS FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),
    CONSTRAINT FK_BOOKINGS_ROOMS FOREIGN KEY (ROOM_ID)
        REFERENCES ROOMS(ROOM_ID),
    CONSTRAINT FK_BOOKINGS_CANCELLED_BY FOREIGN KEY (CANCELLED_BY)
        REFERENCES USERS(USER_ID),
    CONSTRAINT FK_BOOKINGS_DECIDED_BY FOREIGN KEY (DECIDED_BY)
        REFERENCES USERS(USER_ID)
    -- Deliberately NOT declared, to match the live database:
    --   FK_BOOKINGS_APPROVED_BY (APPROVED_BY -> USERS)
    --   FK_BOOKINGS_ORIGINAL    (ORIGINAL_BOOKING_ID -> BOOKINGS)
    --   FK_BOOKINGS_MODIFIED_BY (MODIFIED_BY -> USERS)
    -- The latter two are declared by add_booking_revision_tracking.sql but are
    -- absent live. Adding them to a new environment is reasonable; just be aware
    -- existing environments do not have them.
);

-- 7. NOTIFICATIONS
CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    TYPE VARCHAR2(50) NOT NULL,
    CONTENT VARCHAR2(1000),
    STATUS VARCHAR2(20) CHECK (STATUS IN ('Read', 'Unread')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_NOTIFICATIONS_USERS FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
);

-- 8. MAINTENANCE
CREATE TABLE MAINTENANCE (
    MAINTENANCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROOM_ID NUMBER NOT NULL,
    START_TIME TIMESTAMP NOT NULL,
    END_TIME TIMESTAMP NOT NULL,
    DESCRIPTION VARCHAR2(1000),
    STATUS VARCHAR2(20) CHECK (STATUS IN ('Scheduled', 'In Progress', 'Completed')),
    CONSTRAINT FK_MAINTENANCE_ROOMS FOREIGN KEY (ROOM_ID)
        REFERENCES ROOMS(ROOM_ID)
);

-- 9. SYSTEM_LOGS
-- The previous definition here named these columns ACTION, DETAILS and
-- TIMESTAMP. None of those exist. Anything written against that definition fails
-- with ORA-00904; the live column names are below.
CREATE TABLE SYSTEM_LOGS (
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER,
    ACTION_TYPE VARCHAR2(100) NOT NULL,
    CHANGE_DETAILS VARCHAR2(1000),
    LOG_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    -- Which table and row the entry concerns, e.g. 'BOOKINGS' / '4242'.
    TABLE_NAME VARCHAR2(100),
    RECORD_ID VARCHAR2(100),
    CONSTRAINT FK_SYSTEM_LOGS_USERS FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
);

--10 . ICONS
CREATE TABLE ICONS (
    ICON_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ICON_NAME VARCHAR2(100) UNIQUE NOT NULL,
    ICON_CLASS VARCHAR2(100) NOT NULL       -- CSS class for the icon (e.g., FontAwesome class)
);
