-- ========================================
-- Room Reservation System Schema
-- ========================================
--
-- Reconciled against the live development schema (CONFROOM on inside2_docmd)
-- on 2026-07-29 by querying ALL_TAB_COLUMNS and ALL_CONSTRAINTS.
--
-- This file had drifted badly and was actively misleading: it described
-- SYSTEM_LOGS as ACTION/DETAILS/TIMESTAMP when the live columns are
-- ACTION_TYPE/CHANGE_DETAILS/LOG_TIMESTAMP, and BOOKINGS.STATUS as
-- CHECK (STATUS IN ('Confirmed','Cancelled')) when the live values are
-- pending/approved/rejected/cancelled/archived. It also would not run: the ROOMS
-- definition was missing a comma and AMENITIES was missing its terminating
-- semicolon. All of that is corrected below.
--
-- Columns added by later migrations are now folded in and marked with the
-- migration that owns them, so this file matches what a fresh environment needs:
--   * add_booking_revision_tracking.sql          -> BOOKINGS revision columns
--   * add_reservation_for_and_decision_audit.sql -> BOOKINGS booked-for + audit
--   * notification_preferences.sql               -> NOTIFICATION_TYPES / _PREFERENCES
--   * system_notification_controls.sql           -> notification control tables
--   * add_notification_reminder_log.sql          -> NOTIFICATION_REMINDER_LOG
-- Those files remain the migration path for existing environments; this file is
-- the consolidated picture.
--
-- KNOWN DRIFT STILL PRESENT IN THE LIVE SCHEMA (documented, not "fixed" here):
--   * BOOKINGS.APPROVED_BY has no foreign key in the live database, although
--     earlier versions of this file declared FK_BOOKINGS_APPROVED_BY.
--   * FK_BOOKINGS_ORIGINAL and FK_BOOKINGS_MODIFIED_BY are declared by
--     add_booking_revision_tracking.sql but are NOT present live, so that
--     migration's constraint statements never took effect.
--   * USERS.STATUS has no CHECK constraint live, though this file used to
--     declare one. Application code compares it case-insensitively as a result.
-- Verify against the target environment before relying on any of the above.

-- 1. ROLES
CREATE TABLE ROLES (
    ROLE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROLE_NAME VARCHAR2(100) UNIQUE NOT NULL
);

-- 2. USERS
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(50) NOT NULL,
    LAST_NAME VARCHAR2(50) NOT NULL,
    EMPLID NUMBER,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    ROLE_ID NUMBER,
    -- No CHECK constraint live. Code compares this case-insensitively
    -- (UPPER(u.STATUS) = 'ACTIVE') because the stored casing is not enforced.
    STATUS VARCHAR2(20),
    NOTIFICATION_PREFERENCES CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    EMPLID NUMBER(38),
    LASTLOGGEDON TIMESTAMP,
    DATEENTERED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ENTEREDBYID NUMBER(38),
    -- No default live, unlike DATEENTERED.
    DATEMODIFIED TIMESTAMP,
    MODIFIEDBYID NUMBER(38),
    CONSTRAINT FK_USERS_ROLES FOREIGN KEY (ROLE_ID)
        REFERENCES ROLES(ROLE_ID)
);

